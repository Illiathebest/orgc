// Render produces the .rsc script of a RouterOS device (docs/adr/ADR-009).
//
// The script is meant for /import on a device that is reachable while it
// runs: the bridge is created with VLAN filtering off, ports, VLANs and
// addresses are added, the firewall is built, and filtering is switched on
// only by the last command.
//
// Everything in the script is ASCII. RouterOS 6 handles non-ASCII bytes in
// scripts and comments unreliably, so the header and comments here stay in
// English — the one place generated text departs from the Ukrainian
// header ADR-009 gives other formats.
func (p Platform) Render(m *ir.Model, d *ir.Device) []backend.File {
	r := &script{m: m, d: d, site: d.Site, gateway: d.Site.Gateway == d}
	r.plan()
	r.header()
	r.bridge()
	r.addresses()
	if r.gateway {
		r.uplinks()
		r.dhcp()
		r.firewall(p)
		r.nat()
	} else {
		r.route()
	}
	r.line("")
	r.line("/interface bridge")
	r.line("set [find name=bridge] vlan-filtering=yes")
	return []backend.File{{
		Path: path.Join("configs", d.Site.Name, d.Name+".rsc"),
		Data: []byte(r.b.String()),
	}}
}

type portKind int

const (
	uplink portKind = iota
	trunk
	access
)

type port struct {
	name    string
	kind    portKind
	nets    []*ir.Network // trunk: carried networks; access: its one network
	backup  bool          // uplink of a backup link
	standby bool          // trunk of a standby link: STP keeps it blocked
	comment string
}

type script struct {
	m       *ir.Model
	d       *ir.Device
	site    *ir.Site
	gateway bool
	ports   []port
	b       strings.Builder
}

func (r *script) line(s string) { r.b.WriteString(s + "\n") }

func (r *script) section(title, menu string) {
	r.line("")
	r.line("# " + title)
	r.line(menu)
}

// plan decides what every port of the device does: from the model for a
// site with links, by platform convention otherwise (ADR-009, decision 3
// and its amendment). Ports the model does not mention are not touched.
func (r *script) plan() {
	seen := map[string]bool{}
	add := func(p port) {
		if seen[p.name] {
			return
		}
		seen[p.name] = true
		r.ports = append(r.ports, p)
	}

	if r.gateway {
		for _, u := range r.site.Uplinks {
			name := "ether1"
			if u.Port != nil {
				if u.Port.Device != r.d {
					continue
				}
				name = u.Port.Port
			}
			add(port{name: name, kind: uplink, backup: u.Kind == ir.UplinkBackup, comment: "uplink " + u.Name})
		}
		if len(r.site.Uplinks) == 0 && len(r.site.Links) == 0 {
			add(port{name: "ether1", kind: uplink, comment: "uplink"})
		}
	}

	if len(r.site.Links) > 0 {
		for _, l := range r.site.Links {
			for _, end := range []struct{ here, there *ir.PortRef }{{&l.A, &l.B}, {&l.B, &l.A}} {
				if end.here.Device == r.d {
					comment := "trunk to " + end.there.String()
					if l.Standby {
						comment = "standby trunk to " + end.there.String()
					}
					add(port{name: end.here.Port, kind: trunk, nets: carried(l, r.site), standby: l.Standby, comment: comment})
				}
			}
		}
	} else if r.gateway {
		// ether5 stays out: on RB750 it is the emergency WinBox port.
		for _, name := range []string{"ether2", "ether3", "ether4"} {
			add(port{name: name, kind: trunk, nets: r.site.Networks, comment: "trunk (convention)"})
		}
	} else {
		add(port{name: "ether1", kind: trunk, nets: r.site.Networks, comment: "trunk to gateway (convention)"})
	}

	for _, ap := range r.d.AccessPorts {
		if ap.Network.Net == nil {
			continue
		}
		for _, name := range ap.Ports {
			add(port{name: name, kind: access, nets: []*ir.Network{ap.Network.Net}, comment: "access " + ap.Network.Name})
		}
	}
	for _, s := range r.site.Servers {
		if s.Port == nil || s.Port.Device != r.d {
			continue
		}
		if n := networkOf(r.site, s.IP); n != nil {
			add(port{name: s.Port.Port, kind: access, nets: []*ir.Network{n}, comment: "server " + s.Name})
		}
	}
}

func carried(l *ir.Link, s *ir.Site) []*ir.Network {
	var out []*ir.Network
	for _, n := range s.Networks {
		if l.Carries(n) {
			out = append(out, n)
		}
	}
	return out
}

func networkOf(s *ir.Site, a netip.Addr) *ir.Network {
	for _, n := range s.Networks {
		if n.Prefix.Masked().Contains(a) {
			return n
		}
	}
	return nil
}

func (r *script) header() {
	r.line("# Generated by orgc from " + path.Base(strings.ReplaceAll(r.m.File, `\`, "/")) + ". Do not edit by hand.")
	r.line(fmt.Sprintf("# Device %s (%s), site %s, RouterOS %s.", r.d.Name, r.d.Role, r.site.Name, r.d.OSVersion))
	r.line("# Import on a device reset with no default configuration (/system reset-configuration no-defaults=yes).")
	r.line("")
	r.line("/system identity")
	r.line("set name=" + r.d.Name)
}

func ifname(n *ir.Network) string { return "vlan" + strconv.Itoa(n.VLAN) + "-" + n.Name }

// RSTP on every bridge (docs/adr/ADR-009, amendment 2026-10-14): the site's
// gateway is the root, and a standby link's ports carry the highest cost,
// so that once STP converges the active topology is the tree verify
// judged. One instance for all VLANs.
const (
	rootPriority    = "0x1000"
	defaultPriority = "0x8000"
	standbyCost     = 200000000
)

func (r *script) bridge() {
	r.section("Bridge with VLAN filtering and RSTP; filtering is switched on at the end.", "/interface bridge")
	priority := defaultPriority
	if r.gateway {
		priority = rootPriority
	}
	r.line("add name=bridge vlan-filtering=no protocol-mode=rstp priority=" + priority + " comment=orgc")

	var bridged []port
	for _, p := range r.ports {
		if p.kind != uplink {
			bridged = append(bridged, p)
		}
	}
	if len(bridged) > 0 {
		r.line("/interface bridge port")
	}
	for _, p := range bridged {
		switch p.kind {
		case trunk:
			cost := ""
			if p.standby {
				cost = " path-cost=" + strconv.Itoa(standbyCost)
			}
			r.line(fmt.Sprintf("add bridge=bridge interface=%s frame-types=admit-only-vlan-tagged ingress-filtering=yes%s comment=\"%s\"", p.name, cost, p.comment))
		case access:
			n := p.nets[0]
			horizon := ""
			if n.Isolated {
				// Ports sharing a horizon do not forward to each other:
				// hosts of an isolated network reach the gateway only.
				horizon = " horizon=" + strconv.Itoa(n.VLAN)
			}
			r.line(fmt.Sprintf("add bridge=bridge interface=%s pvid=%d frame-types=admit-only-untagged-and-priority-tagged ingress-filtering=yes%s comment=\"%s\"", p.name, n.VLAN, horizon, p.comment))
		}
	}

	r.line("/interface bridge vlan")
	for _, n := range r.site.Networks {
		tagged := []string{"bridge"}
		var untagged []string
		for _, p := range r.ports {
			for _, pn := range p.nets {
				if pn != n {
					continue
				}
				if p.kind == trunk {
					tagged = append(tagged, p.name)
				} else if p.kind == access {
					untagged = append(untagged, p.name)
				}
			}
		}
		u := ""
		if len(untagged) > 0 {
			u = " untagged=" + strings.Join(untagged, ",")
		}
		r.line(fmt.Sprintf("add bridge=bridge vlan-ids=%d tagged=%s%s comment=%s", n.VLAN, strings.Join(tagged, ","), u, n.Name))
	}
}

// own lists the device's addresses per network: the gateway address of every
// network it routes (on the site's gateway) and its mgmt_ip.
func (r *script) own() []struct {
	n     *ir.Network
	addrs []netip.Addr
} {
	var out []struct {
		n     *ir.Network
		addrs []netip.Addr
	}
	for _, n := range r.site.Networks {
		var addrs []netip.Addr
		if r.gateway && n.Gateway.IsValid() {
			addrs = append(addrs, n.Gateway)
		}
		if n.Prefix.Masked().Contains(r.d.MgmtIP) && (len(addrs) == 0 || addrs[0] != r.d.MgmtIP) {
			addrs = append(addrs, r.d.MgmtIP)
		}
		if len(addrs) > 0 {
			out = append(out, struct {
				n     *ir.Network
				addrs []netip.Addr
			}{n, addrs})
		}
	}
	return out
}

func (r *script) addresses() {
	own := r.own()
	if len(own) == 0 {
		return
	}
	r.section("VLAN interfaces and addresses.", "/interface vlan")
	for _, o := range own {
		r.line(fmt.Sprintf("add interface=bridge name=%s vlan-id=%d", ifname(o.n), o.n.VLAN))
	}
	r.line("/ip address")
	for _, o := range own {
		for _, a := range o.addrs {
			r.line(fmt.Sprintf("add address=%s/%d interface=%s comment=%s", a, o.n.Prefix.Bits(), ifname(o.n), o.n.Name))
		}
	}
}

func (r *script) uplinkPorts() []port {
	var out []port
	for _, p := range r.ports {
		if p.kind == uplink {
			out = append(out, p)
		}
	}
	return out
}

func (r *script) uplinks() {
	ups := r.uplinkPorts()
	if len(ups) == 0 {
		return
	}
	r.section("Uplinks: address from the provider, default route; backup with a higher distance.", "/interface list")
	r.line("add name=WAN comment=orgc")
	r.line("/interface list member")
	for _, p := range ups {
		r.line(fmt.Sprintf("add list=WAN interface=%s", p.name))
	}
	// The uplink port belongs to the model: a DHCP client already on it — the
	// factory default of CHR on ether1 — is replaced, not left to make the
	// import fail with "dhcp-client on that interface already exists".
	r.line("/ip dhcp-client")
	for _, p := range ups {
		r.line(fmt.Sprintf("remove [find interface=%s]", p.name))
	}
	for _, p := range ups {
		distance := 1
		if p.backup {
			distance = 2
		}
		r.line(fmt.Sprintf("add interface=%s add-default-route=yes default-route-distance=%d use-peer-dns=no disabled=no comment=\"%s\"", p.name, distance, p.comment))
	}
}

func (r *script) dhcp() {
	var pooled []*ir.Network
	for _, n := range r.site.Networks {
		if n.Pool != nil && n.Gateway.IsValid() {
			pooled = append(pooled, n)
		}
	}
	if len(pooled) == 0 {
		return
	}
	r.section("DHCP servers.", "/ip pool")
	for _, n := range pooled {
		r.line(fmt.Sprintf("add name=pool-%s ranges=%s-%s", n.Name, n.Pool.From, n.Pool.To))
	}
	r.line("/ip dhcp-server")
	for _, n := range pooled {
		r.line(fmt.Sprintf("add name=dhcp-%s interface=%s address-pool=pool-%s disabled=no", n.Name, ifname(n), n.Name))
	}
	r.line("/ip dhcp-server network")
	for _, n := range pooled {
		r.line(fmt.Sprintf("add address=%s gateway=%s comment=%s", n.Prefix.Masked(), n.Gateway, n.Name))
	}
}

// relevant lists the rules a gateway enforces: those touching a network of
// its site or any. Rules are global (docs/data-model.md); a gateway filters
// what passes through it. They come in canonical order — from, to,
// protocol, ports — so that a new rule changes a few neighbouring lines.
func (r *script) relevant() []*ir.Rule {
	touches := func(e ir.Endpoint) bool {
		return e.Kind == ir.EndpointAny || (e.Kind == ir.EndpointNetwork && e.Net != nil && e.Net.Site == r.site)
	}
	var out []*ir.Rule
	for _, rule := range r.m.Rules {
		if !rule.From.Resolved() || !rule.To.Resolved() {
			continue
		}
		if touches(rule.From) || (rule.To.Kind != ir.EndpointInternet && touches(rule.To)) {
			out = append(out, rule)
		}
	}
	sort.SliceStable(out, func(i, j int) bool { return ruleKey(out[i]) < ruleKey(out[j]) })
	return out
}

func ruleKey(r *ir.Rule) string {
	return r.From.Name + "\x00" + r.To.Name + "\x00" + ports(r.Ports)
}

func ports(s ir.PortSet) string {
	if s.Any {
		return ""
	}
	nums := make([]string, len(s.Ports))
	for i, p := range s.Ports {
		nums[i] = strconv.Itoa(p.Port)
	}
	return " protocol=" + string(s.Ports[0].Proto) + " dst-port=" + strings.Join(nums, ",")
}

func src(e ir.Endpoint) string {
	if e.Kind == ir.EndpointAny {
		return " src-address-list=orgc-networks"
	}
	return " src-address=" + e.Net.Prefix.Masked().String()
}

func dst(e ir.Endpoint) string {
	switch e.Kind {
	case ir.EndpointAny:
		return " dst-address-list=orgc-networks"
	case ir.EndpointInternet:
		return " out-interface-list=WAN"
	}
	return " dst-address=" + e.Net.Prefix.Masked().String()
}

func comment(rule *ir.Rule) string {
	return " comment=\"" + rule.From.Name + " -> " + rule.To.Name + "\""
}

func (r *script) firewall(p Platform) {
	rules := r.relevant()

	r.section("Networks of the model: what any means in a rule.", "/ip firewall address-list")
	for _, n := range r.m.Networks {
		r.line(fmt.Sprintf("add list=orgc-networks address=%s comment=%s", n.Prefix.Masked(), n.Name))
	}

	r.section("Input: traffic to the gateway itself. Default deny.", "/ip firewall filter")
	r.line("add chain=input action=accept connection-state=established,related comment=\"established, related\"")
	r.line("add chain=input action=drop connection-state=invalid comment=invalid")
	if nc := r.m.ControlNode.Network.Net; nc != nil {
		var mp []string
		for _, pp := range p.ManagementPorts(r.d.OSVersion) {
			mp = append(mp, strconv.Itoa(pp.Port))
		}
		if len(mp) > 0 {
			r.line(fmt.Sprintf("add chain=input action=accept src-address=%s dst-address=%s protocol=tcp dst-port=%s comment=\"management from %s\"",
				nc.Prefix.Masked(), r.d.MgmtIP, strings.Join(mp, ","), nc.Name))
		}
	}
	own := r.own()
	for _, rule := range rules {
		for _, o := range own {
			if rule.To.Kind == ir.EndpointInternet || (rule.To.Kind == ir.EndpointNetwork && rule.To.Net != o.n) {
				continue
			}
			for _, a := range o.addrs {
				r.line("add chain=input action=accept" + src(rule.From) + " dst-address=" + a.String() + ports(rule.Ports) + comment(rule))
			}
		}
	}
	for _, o := range own {
		if o.n.Pool != nil {
			r.line(fmt.Sprintf("add chain=input action=accept protocol=udp dst-port=67 in-interface=%s comment=\"dhcp %s\"", ifname(o.n), o.n.Name))
		}
	}
	r.line("add chain=input action=drop comment=\"default deny\"")

	r.line("")
	r.line("# Forward: traffic between networks and to the internet. Default deny.")
	r.line("add chain=forward action=accept connection-state=established,related comment=\"established, related\"")
	r.line("add chain=forward action=drop connection-state=invalid comment=invalid")
	for _, rule := range rules {
		r.line("add chain=forward action=accept" + src(rule.From) + dst(rule.To) + ports(rule.Ports) + comment(rule))
	}
	r.line("add chain=forward action=drop comment=\"default deny\"")
}

func (r *script) nat() {
	var sources []*ir.Network
	seen := map[*ir.Network]bool{}
	for _, rule := range r.relevant() {
		if rule.To.Kind != ir.EndpointInternet {
			continue
		}
		for _, n := range r.site.Networks {
			if (rule.From.Kind == ir.EndpointAny || rule.From.Net == n) && !seen[n] {
				seen[n] = true
				sources = append(sources, n)
			}
		}
	}
	if len(sources) == 0 || len(r.uplinkPorts()) == 0 {
		return
	}
	sort.SliceStable(sources, func(i, j int) bool { return indexOf(r.site, sources[i]) < indexOf(r.site, sources[j]) })
	r.section("NAT: networks with a rule to the internet.", "/ip firewall nat")
	for _, n := range sources {
		r.line(fmt.Sprintf("add chain=srcnat action=masquerade src-address=%s out-interface-list=WAN comment=\"%s -> internet\"", n.Prefix.Masked(), n.Name))
	}
}

func indexOf(s *ir.Site, n *ir.Network) int {
	for i, x := range s.Networks {
		if x == n {
			return i
		}
	}
	return -1
}

// route gives a device that is not the gateway its way out: through the
// gateway of its mgmt network.
func (r *script) route() {
	for _, n := range r.site.Networks {
		if n.Prefix.Masked().Contains(r.d.MgmtIP) && n.Gateway.IsValid() {
			r.section("Default route through the site gateway.", "/ip route")
			r.line("add gateway=" + n.Gateway.String() + " comment=orgc")
			return
		}
	}
}
